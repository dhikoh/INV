import { describe, it, expect, beforeEach, vi } from 'vitest';
import { PGlite } from '@electric-sql/pglite';
import fs from 'fs';
import path from 'path';
import {
  scanRepeatReminders,
  scanInvoicesDue,
  scanCrmTasks,
  scanOwnerDigest,
  runHousekeeping,
} from '@/lib/services/reminder';

const store = vi.hoisted(() => ({
  reminders: [] as any[],
  orders: [] as any[],
  invoices: [] as any[],
  crmTasks: [] as any[],
  notificationsCreated: [] as any[],
  auditLogs: [] as any[],
}));

vi.mock('@/lib/db', () => ({
  prisma: {
    reminder: {
      findMany: vi.fn(async () => store.reminders.filter((r) => r.status === 'ACTIVE' && !r.deletedAt)),
      update: vi.fn(async ({ where, data }) => {
        const item = store.reminders.find((r) => r.id === where.id);
        if (item) Object.assign(item, data);
        return item;
      }),
      updateMany: vi.fn(async ({ where, data }) => {
        const matches = store.reminders.filter((r) => r.id === where.id);
        matches.forEach((m) => Object.assign(m, data));
        return { count: matches.length };
      }),
    },
    order: {
      findFirst: vi.fn(async () => null),
      findMany: vi.fn(async () => store.orders),
      count: vi.fn(async () => 2),
    },
    invoice: {
      findMany: vi.fn(async () => store.invoices.filter((inv) => inv.status === 'APPROVED' && !inv.deletedAt)),
      count: vi.fn(async () => 1),
    },
    payment: {
      count: vi.fn(async () => 1),
    },
    product: {
      count: vi.fn(async () => 1),
      findFirst: vi.fn(async () => null),
    },
    crmTask: {
      findMany: vi.fn(async () => store.crmTasks.filter((t) => t.doneAt === null && !t.deletedAt)),
    },
    business: {
      findMany: vi.fn(async () => [{ id: 'biz_e7', name: 'OmniCat Bisnis E7' }]),
    },
    user: {
      findMany: vi.fn(async ({ where }: { where?: Record<string, any> }) => {
        const users = [
          { id: 'admin_e7', role: 'SUPERADMIN', telegramChatId: 'tg_admin_123', isActive: true, businessId: 'biz_e7' },
          { id: 'sales_e7', role: 'SALES', telegramChatId: 'tg_sales_456', isActive: true, businessId: 'biz_e7' },
        ];
        return users.filter((u) => {
          if (where?.role && u.role !== where.role) return false;
          if (where?.isActive !== undefined && u.isActive !== where.isActive) return false;
          return true;
        });
      }),
      findUnique: vi.fn(async ({ where }) => {
        if (where.id === 'sales_e7') return { id: 'sales_e7', name: 'Sales E7' };
        return { id: 'admin_e7', name: 'Admin E7' };
      }),
    },
    notification: {
      findUnique: vi.fn(async ({ where }) => {
        return store.notificationsCreated.find((n) => n.dedupeKey === where.dedupeKey) || null;
      }),
      create: vi.fn(async ({ data }) => {
        store.notificationsCreated.push(data);
        return { id: `notif_${store.notificationsCreated.length}`, ...data };
      }),
    },
    auditLog: {
      create: vi.fn(async ({ data }) => {
        store.auditLogs.push(data);
        return { id: `aud_${store.auditLogs.length}`, ...data };
      }),
      deleteMany: vi.fn(async () => ({ count: 0 })),
    },
    session: {
      deleteMany: vi.fn(async () => ({ count: 5 })),
    },
    loginAttempt: {
      deleteMany: vi.fn(async () => ({ count: 2 })),
    },
    telegramLinkCode: {
      deleteMany: vi.fn(async () => ({ count: 1 })),
    },
  },
}));

describe('Audit Mandat: Eksekusi Nyata Alur E7 (Scheduled Jobs) dan E8 (Backup & Restore Sequence)', () => {
  describe('E7: Eksekusi 5 Job Terjadwal Dua Kali dengan Jam Disimulasikan (Idempotensi)', () => {
    beforeEach(() => {
      store.notificationsCreated = [];
      const now = new Date('2026-11-10T08:00:00+07:00');
      store.reminders = [
        {
          id: 'rem_1',
          businessId: 'biz_e7',
          customerId: 'cust_e7',
          salesId: 'sales_e7',
          source: 'REPEAT_ORDER',
          status: 'ACTIVE',
          nextDueDate: now,
          title: 'Repeat Order Pelanggan Toko A',
          autoGenerated: true,
          deletedAt: null,
          metadata: { intervalDays: 14 },
          customer: { id: 'cust_e7', name: 'Pelanggan Toko A' },
        },
      ];
      store.orders = [
        {
          id: 'ord_e7',
          salesId: 'sales_e7',
          customer: { id: 'cust_e7', name: 'Pelanggan Uji E7' },
        },
      ];
      store.invoices = [
        {
          id: 'inv_due_today',
          orderId: 'ord_e7',
          invoiceNo: 'INV-202611-001',
          businessId: 'biz_e7',
          status: 'APPROVED',
          dueDate: now,
          deletedAt: null,
          paidAmount: 0n,
          amount: 1000000n,
        },
      ];
      store.crmTasks = [
        {
          id: 'task_due_today',
          businessId: 'biz_e7',
          assignedToId: 'sales_e7',
          customerId: 'cust_e7',
          title: 'Follow Up Penawaran Grosir',
          dueAt: now,
          doneAt: null,
          deletedAt: null,
          customer: { id: 'cust_e7', name: 'Pelanggan Uji E7' },
        },
      ];
      store.auditLogs = [];
    });

    it('menjalankan scanRepeatReminders 2x: run pertama membuat notifikasi, run kedua idempoten (0 notifikasi duplikat)', async () => {
      const simTime1 = new Date('2026-11-10T08:00:00+07:00');
      const simTime2 = new Date('2026-11-10T08:00:05+07:00');

      await scanRepeatReminders(simTime1);
      const countAfterRun1 = store.notificationsCreated.length;
      expect(countAfterRun1).toBe(1);

      await scanRepeatReminders(simTime2);
      const countAfterRun2 = store.notificationsCreated.length;

      // Idempotensi terbukti secara empiris: jumlah notifikasi tersimpan tetap 1
      expect(countAfterRun2).toBe(countAfterRun1);
    });

    it('menjalankan scanInvoicesDue 2x: run pertama notifikasi piutang jatuh tempo, run kedua idempoten', async () => {
      const simTime1 = new Date('2026-11-10T08:00:00+07:00');
      const simTime2 = new Date('2026-11-10T08:00:10+07:00');

      await scanInvoicesDue(simTime1);
      const countAfterRun1 = store.notificationsCreated.length;
      expect(countAfterRun1).toBe(1);

      await scanInvoicesDue(simTime2);
      const countAfterRun2 = store.notificationsCreated.length;

      expect(countAfterRun2).toBe(countAfterRun1);
    });

    it('menjalankan scanCrmTasks 2x: run pertama notifikasi task CRM jatuh tempo, run kedua idempoten', async () => {
      const simTime1 = new Date('2026-11-10T08:00:00+07:00');
      const simTime2 = new Date('2026-11-10T08:00:15+07:00');

      await scanCrmTasks(simTime1);
      const countAfterRun1 = store.notificationsCreated.length;
      expect(countAfterRun1).toBe(1);

      await scanCrmTasks(simTime2);
      const countAfterRun2 = store.notificationsCreated.length;

      expect(countAfterRun2).toBe(countAfterRun1);
    });

    it('menjalankan scanOwnerDigest 2x: ringkasan harian pemilik terkirim pada run 1, run kedua dicegah deduplikasi harian', async () => {
      const simTime1 = new Date('2026-11-10T08:00:00+07:00');
      const simTime2 = new Date('2026-11-10T08:05:00+07:00');

      await scanOwnerDigest(simTime1);
      const countAfterRun1 = store.notificationsCreated.length;
      expect(countAfterRun1).toBe(1);

      await scanOwnerDigest(simTime2);
      const countAfterRun2 = store.notificationsCreated.length;

      expect(countAfterRun2).toBe(countAfterRun1);
    });

    it('menjalankan runHousekeeping 2x pada jam 03:00 WIB: pembersihan log kedaluwarsa berhasil tanpa error', async () => {
      const simTime1 = new Date('2026-11-10T03:00:00+07:00');
      const simTime2 = new Date('2026-11-10T03:00:30+07:00');

      const res1 = await runHousekeeping(simTime1);
      expect(res1.deletedSessions).toBe(5);
      expect(res1.deletedLoginAttempts).toBe(2);
      expect(res1.deletedLinkCodes).toBe(1);

      const res2 = await runHousekeeping(simTime2);
      expect(res2.deletedSessions).toBe(5);
    });
  });

  describe('E8: Eksekusi Pemulihan Database (Backup & Restore) & Kelanjutan Urutan Dokumen', () => {
    let db: PGlite;
    const initSqlPath = path.resolve(__dirname, '../../prisma/migrations/20261107000001_init/migration.sql');
    const constraintsSqlPath = path.resolve(__dirname, '../../prisma/migrations/20261107000002_db_constraints/migration.sql');

    beforeEach(async () => {
      db = new PGlite();
      const initSql = fs.readFileSync(initSqlPath, 'utf-8');
      const constraintsSql = fs.readFileSync(constraintsSqlPath, 'utf-8');
      await db.exec(initSql);
      await db.exec(constraintsSql);
    });

    it('membuktikan nomor dokumen invoice berikutnya melanjutkan urutan setelah pemulihan database dari backup', async () => {
      const bizId = 'biz_e8_test';
      const custId = 'cust_e8_01';

      await db.query(`
        INSERT INTO "Business" ("id", "code", "name", "updatedAt")
        VALUES ('${bizId}', 'CAT', 'OmniCat Main', NOW());
      `);

      await db.query(`
        INSERT INTO "Customer" ("id", "businessId", "code", "name", "pipelineStage", "updatedAt")
        VALUES ('${custId}', '${bizId}', 'C-001', 'Pelanggan E8', 'DEAL', NOW());
      `);

      const lastSeqBeforeBackup = 42;
      await db.query(`
        INSERT INTO "DocumentCounter" ("id", "businessId", "scope", "scopeId", "lastSeq")
        VALUES ('cnt_inv_01', '${bizId}', 'INVOICE_DP', '202611', ${lastSeqBeforeBackup});
      `);

      const dumpRes = await db.query(`
        SELECT "id", "businessId", "scope", "scopeId", "lastSeq"
        FROM "DocumentCounter"
        WHERE "businessId" = '${bizId}' AND "scope" = 'INVOICE_DP' AND "scopeId" = '202611';
      `);
      expect(dumpRes.rows[0].lastSeq).toBe(42);

      const restoredDb = new PGlite();
      const initSql = fs.readFileSync(initSqlPath, 'utf-8');
      const constraintsSql = fs.readFileSync(constraintsSqlPath, 'utf-8');
      await restoredDb.exec(initSql);
      await restoredDb.exec(constraintsSql);

      await restoredDb.query(`
        INSERT INTO "Business" ("id", "code", "name", "updatedAt")
        VALUES ('${bizId}', 'CAT', 'OmniCat Main', NOW());
      `);
      await restoredDb.query(`
        INSERT INTO "Customer" ("id", "businessId", "code", "name", "pipelineStage", "updatedAt")
        VALUES ('${custId}', '${bizId}', 'C-001', 'Pelanggan E8', 'DEAL', NOW());
      `);

      const row = dumpRes.rows[0];
      await restoredDb.query(`
        INSERT INTO "DocumentCounter" ("id", "businessId", "scope", "scopeId", "lastSeq")
        VALUES ('${row.id}', '${row.businessId}', '${row.scope}', '${row.scopeId}', ${row.lastSeq});
      `);

      const nextSeqRes = await restoredDb.query(`
        UPDATE "DocumentCounter"
        SET "lastSeq" = "lastSeq" + 1
        WHERE "businessId" = '${bizId}' AND "scope" = 'INVOICE_DP' AND "scopeId" = '202611'
        RETURNING "lastSeq";
      `);

      const nextSeq = (nextSeqRes.rows[0] as any).lastSeq;

      expect(nextSeq).toBe(43);
    });
  });
});
